function png(b64: string): Response {
  // Uint8Array.from(atob(...)) — sin Buffer, que no existe en workerd.
  const bin = atob(b64);
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new Response(bytes, {
    status: 200,
    headers: {
      "Content-Type": "image/png",
      // Un año: si la marca cambia, cambia el nombre del archivo.
      "Cache-Control": "public, max-age=31536000, immutable",
    },
  });
}

export const serveFavicon = (): Response => png(FAVICON_B64);
export const serveIcon = (): Response => png(ICON_B64);
